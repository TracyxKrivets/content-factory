const path = require("path");
const APP = require("url").pathToFileURL(path.join(__dirname, "../web/dist/content-factory.html")).href;
const FIX = (f) => path.join(__dirname, "fixtures", f);
const OUT = (f) => path.join(__dirname, "out", f);
const { chromium } = require("playwright"); const fs = require("fs");
const URL = APP;
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 950 }, acceptDownloads: true });
  const p = await ctx.newPage();
  p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
  p.on("console", (m) => m.type() === "error" && !/fonts|ERR_|net::/.test(m.text()) && console.log("CONSOLE", m.text().slice(0, 300)));
  const t0 = Date.now();
  await p.goto(URL);
  await p.waitForSelector("text=GENERATE VIDEOS", { timeout: 15000 });
  console.log("opened in", Date.now() - t0, "ms");
  await p.screenshot({ path: OUT("1-home.png") });
  await p.fill("textarea.big", "Make 2 did you know shorts about octopuses");
  await p.click("text=GENERATE VIDEOS");
  await p.waitForFunction(() => location.hash.startsWith("#project-"), null, { timeout: 15000 });
  await p.waitForTimeout(5000);
  await p.screenshot({ path: OUT("2-working.png"), fullPage: true });
  const t1 = Date.now();
  await p.waitForSelector("text=All done", { timeout: 300000 }).catch(async (e) => { await p.screenshot({ path: OUT("err.png"), fullPage: true }); throw e; });
  console.log("2 videos done in", Math.round((Date.now() - t1) / 1000), "s; title:", await p.title());
  await p.screenshot({ path: OUT("3-done.png"), fullPage: true });
  const [dl] = await Promise.all([p.waitForEvent("download"), p.click("text=DOWNLOAD ALL")]);
  await dl.saveAs(OUT("all.zip")); console.log("zip:", dl.suggestedFilename());
  const [d1] = await Promise.all([p.waitForEvent("download"), p.locator("button:has-text('⬇ DOWNLOAD')").nth(1).click()]);
  await d1.saveAs(FIX("one.mp4")); console.log("single:", d1.suggestedFilename());
  await b.close();
})();
